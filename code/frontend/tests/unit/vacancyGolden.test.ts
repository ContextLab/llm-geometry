// --- 1. u(stem), exactly ---------------------------------------------------------------

describe("u(stem) is THE SAME double in both languages (§4, departure 2)", () => {
  const keep = effectiveKeepSet([]);

  it("pins 24 stems spanning eligible/ineligible and both budgets", () => {
    expect(golden.stems).toHaveLength(24);
    // The span §11 asks for is a property of the list, so it is asserted rather than
    // assumed: a fixture of 24 ordinary words would pin nothing about the eligibility test.
    expect(golden.stems.some((s) => s.eligible)).toBe(true);
    expect(golden.stems.some((s) => !s.eligible)).toBe(true);
    expect(golden.stems.some((s) => s.inDolchFull)).toBe(true);
    expect(golden.stems.some((s) => s.inCorpus && !s.inDolchFull)).toBe(true);
    expect(golden.stems.some((s) => !s.inCorpus && s.inDolchFull)).toBe(true);
  });

  for (const entry of golden.stems) {
    it(`${entry.stem}: exact u at both seeds, and the same eligibility verdict`, () => {
      // `toBe` on a double is deliberate. The `>> 11` in `vacancyU` exists precisely so
      // that this is bit-exact; a tolerance here would hide the bug it was added to fix.
      expect(vacancyU(entry.stem, 0)).toBe(entry.u["0"]);
      expect(vacancyU(entry.stem, 7)).toBe(entry.u["7"]);
      const [stem, suffix] = stemAndSuffix(entry.stem);
      expect(stem).toBe(entry.stemOf);
      expect(suffix).toBe(entry.suffixOf);
      expect(isEligible(stem, keep)).toBe(entry.eligible);
      expect(DOMAIN.includes(entry.stem)).toBe(entry.inDomain);
      expect(CORPUS_TYPES.has(entry.stem)).toBe(entry.inCorpus);
      expect(BUDGET_WORDS.includes(entry.stem)).toBe(entry.inDolchFull);
    });
  }
});

// --- 2. the maps ------------------------------------------------------------------------

describe("the stem -> nonce map (§5.2)", () => {
  for (const gm of golden.maps) {
    it(`${gm.label}: reproduces Python's assignment`, () => {
      const params = vacancyParams({
        seed: gm.seed,
        matchProsody: gm.matchProsody,
        mint: gm.mint,
        // The control labels differ from the mapped condition only in knobs that do not
        // reach minting, so the map is a pure function of (domain, seed, matchProsody);
        // building it from the seed and the flag alone is itself part of the claim.
      });
      const vmap = mapFor(params);
      expect(vmap.remintRounds).toBe(gm.remintRounds);
      expect(vmap.bijective).toBe(gm.bijective);
      expect(vmap.injectiveAtEveryP).toBe(gm.injectiveAtEveryP);
      expect(vmap.imageSize).toBe(gm.imageSize);
      expect(vmap.domain.size).toBe(gm.domainSize);
      expect(vmap.mapping.size).toBe(gm.mappingSize);
      expect(mappingSha256(vmap.mapping)).toBe(gm.mappingSha256);

      if (gm.mapping !== null) {
        // The full map, pair by pair — §11 asks for every one at seeds 0 and 7. Both
        // directions, so neither a missing stem nor an extra one can pass.
        const expectedStems = Object.keys(gm.mapping);
        expect(expectedStems).toHaveLength(vmap.mapping.size);
        const mismatched: string[] = [];
        for (const [stem, nonce] of Object.entries(gm.mapping)) {
          if (vmap.mapping.get(stem) !== nonce) {
            mismatched.push(`${stem}: ${vmap.mapping.get(stem)} != ${nonce}`);
          }
        }
        expect(mismatched).toEqual([]);
        for (const stem of vmap.mapping.keys()) expect(gm.mapping[stem]).toBeDefined();
      }
      if (gm.sampleNonces !== undefined) {
        for (const [stem, nonce] of Object.entries(gm.sampleNonces)) {
          expect(vmap.mapping.get(stem) ?? null).toBe(nonce);
        }
      }
    });
  }
});

// --- 3-4, 6-8. the measured cases -------------------------------------------------------

describe("the vacated corpus, its statistics and its id stream", () => {
  for (const gc of golden.cases) {
    it(`${gc.label}: matches Python`, () => {
      const params = paramsOf(gc);
      const vmap = mapFor(params);
      // Order matters and it is Python's: the rewrite runs first, because under
      // `consistent = false` it registers the minted stress patterns that the statistics
      // then score the vacated side with.
      const vacated = vacateText(CORPUS, vmap, params);
      const stats: VacancyStats = vacancyStats(CORPUS, vacated, vmap, params);

      // A field the fixture flags as divergent is asserted against the MEASURED TypeScript
      // reading, AND its Python reading is asserted to still differ. Two exact assertions,
      // not a widened tolerance and not a skip: either stack changing fails one of them.
      const diverging = new Map((gc.knownDivergence?.fields ?? []).map((f) => [f.field, f]));
      const consumed = new Set<string>();
      function reference(field: string): string | number | boolean {
        const d = diverging.get(field);
        if (d === undefined) return goldenField(gc, field);
        consumed.add(field);
        expect(goldenField(gc, field), `${gc.label}.${field} (python reading)`).toBe(d.python);
        expect(d.python).not.toBe(d.typescript);
        return d.typescript;
      }

      // §11: strings compare EXACTLY.
      expect(vacated.slice(0, 400), `${gc.label}.head400`).toBe(reference("head400"));
      expect(vacated.length, `${gc.label}.vacatedChars`).toBe(reference("vacatedChars"));
      expect(sha256(vacated), `${gc.label}.vacatedSha256`).toBe(reference("vacatedSha256"));

      for (const field of EXACT_STATS) {
        expect(stats[field], `${gc.label}.${field}`).toBe(reference(`stats.${field}`));
      }
      for (const field of FLOAT_STATS) {
        expectClose(stats[field], reference(`stats.${field}`) as number, `${gc.label}.${field}`);
      }
      // No stale exemption may sit in the fixture unread.
      expect([...consumed].sort()).toEqual([...diverging.keys()].sort());
      // The three-way stress split is token-weighted and sums to 1 on each side (§10).
      expectClose(
        stats.stressFromTableAfter + stats.stressFromMintedAfter + stats.stressFromRuleAfter,
        1,
        `${gc.label}.stressSplitAfter sums to 1`,
      );

      // §11 stability: the surface form of each pinned stem at this `p`.
      if (gc.stemForms !== null) {
        for (const [stem, form] of Object.entries(gc.stemForms)) {
          expect(transformWord(stem, vmap, params), `${gc.label}.stemForms.${stem}`).toBe(form);
        }
      }

      // §7.2 / §7.3: the id stream under the MAPPED vocabulary.
      if (gc.idStream === null) {
        expect(gc.mapVocabWordsRejects).toBe(true);
        // Both stacks refuse: a mapped vocabulary in a control condition would be a word
        // list matching no corpus, built without error.
        expect(() => mapVocabWords(BUDGET_WORDS, vmap, params)).toThrow();
      } else {
        expect(gc.mapVocabWordsRejects).toBe(false);
        const mapped = mapVocabWords(BUDGET_WORDS, vmap, params);
        expect(mapped).toHaveLength(BUDGET_WORDS.length);
        expect(sha256(mapped.join("\n"))).toBe(gc.idStream.mappedWordsSha256);
        const ids = tokenStream(vacated, new LexVocab(mapped, "dolch", "full"));
        expect(ids.length).toBe(gc.idStream.length);
        expect(ids.slice(0, 16)).toEqual(gc.idStream.first16);
        expect(ids.slice(-16)).toEqual(gc.idStream.last16);
        expect(sha256(ids.join(","))).toBe(gc.idStream.digest);
      }
    });
  }
});

// --- 5. nesting, as explicit sets (SC-701) ---------------------------------------------

describe("nesting is a structural fact, checked against explicit sets (SC-701)", () => {
  const gn = golden.nesting;
  const vmap = mapFor(vacancyParams({ seed: gn.seed }));

  function vacatedStems(p: number): string[] {
    const out: string[] = [];
    for (const stem of vmap.mapping.keys()) if (vacancyU(stem, gn.seed) < p) out.push(stem);
    return out.sort();
  }

  for (const level of gn.levels) {
    it(`p = ${level.p}: the vacated stem set is exactly Python's ${level.stems.length}`, () => {
      expect(vacatedStems(level.p)).toEqual(level.stems);
    });
  }

  it("each level contains the one below it", () => {
    for (let i = 1; i < gn.levels.length; i++) {
      const smaller = new Set(gn.levels[i - 1].stems);
      const larger = new Set(gn.levels[i].stems);
      expect(larger.size).toBeGreaterThan(smaller.size);
      for (const stem of smaller) {
        expect(larger.has(stem), `${stem} vacated at ${gn.levels[i - 1].p} but not later`).toBe(
          true,
        );
      }
    }
    // At p = 1 every eligible stem vacates, since u ∈ [0, 1) by construction (§10).
    const top = gn.levels[gn.levels.length - 1];
    expect(top.p).toBe(1);
    expect(top.stems).toHaveLength(vmap.mapping.size);
  });
});

// --- 6. stability across p (SC-702) -----------------------------------------------------

describe("a stem's nonce is identical at every p where it is vacated (SC-702)", () => {
  for (const gm of golden.maps.filter((m) => m.mapping !== null)) {
    it(`${gm.label}: the pinned stems never change form as p grows`, () => {
      const cases = golden.cases.filter((c) => c.map === gm.label && c.stemForms !== null);
      expect(cases.length).toBeGreaterThan(1);
      const seen = new Map<string, string>();
      for (const gc of cases) {
        const params = paramsOf(gc);
        const vmap = mapFor(params);
        for (const stem of Object.keys(gc.stemForms as Record<string, string>)) {
          const form = transformWord(stem, vmap, params);
          if (form === stem) continue; // not vacated at this p — nothing to be stable about
          const previous = seen.get(stem);
          if (previous !== undefined) expect(form).toBe(previous);
          seen.set(stem, form);
        }
      }
      // The pinned list must actually exercise the property, or this describe is vacuous.
      expect(seen.size).toBeGreaterThan(0);
    });
  }
});

// --- 7. the invariance theorem, as data (SC-703) ---------------------------------------

describe("the id stream is unchanged by vacancy at every p (§7.3, SC-703)", () => {
  it("every mapped-condition case has the SAME token-id digest", () => {
    const withStream = golden.cases.filter((c) => c.idStream !== null);
    // Both seeds, both matchProsody settings, every p — one digest.
    expect(withStream.length).toBeGreaterThanOrEqual(16);
    const digests = new Set(withStream.map((c) => (c.idStream as GoldenIdStream).digest));
    const lengths = new Set(withStream.map((c) => (c.idStream as GoldenIdStream).length));
    expect(digests.size).toBe(1);
    expect(lengths.size).toBe(1);
    expect(withStream.some((c) => c.params.seed === 7)).toBe(true);
    expect(withStream.some((c) => !c.params.matchProsody)).toBe(true);
    expect(withStream.some((c) => c.params.p === 1)).toBe(true);
  });

  it("and that digest is the UNVACATED corpus's own stream", () => {
    // The theorem is that relabelling the vocabulary alongside the corpus leaves training
    // bit-identical, so the p = 0 stream — plain English, plain Dolch — must be it.
    const ids = tokenStream(CORPUS, new LexVocab(BUDGET_WORDS, "dolch", "full"));
    const golden0 = golden.cases.find((c) => c.idStream !== null)?.idStream as GoldenIdStream;
    expect(sha256(ids.join(","))).toBe(golden0.digest);
    expect(ids.length).toBe(golden0.length);
  });
});

// --- 8. the controls really are controls -----------------------------------------------

describe("the control conditions are present and behave as controls (§7.1, SC-705)", () => {
  it("both controls and both matchProsody settings are pinned", () => {
    const labels = golden.cases.map((c) => c.label);
    expect(labels).toContain("control-inconsistent");
    expect(labels).toContain("control-reveal-after-2");
    expect(golden.cases.some((c) => !c.params.consistent)).toBe(true);
    expect(golden.cases.some((c) => c.params.revealAfter > 0)).toBe(true);
    expect(golden.cases.some((c) => c.params.matchProsody)).toBe(true);
    expect(golden.cases.some((c) => !c.params.matchProsody)).toBe(true);
  });

  it("matchProsody = false really mints a different map", () => {
    const withProsody = golden.maps.find((m) => m.label === "seed0");
    const without = golden.maps.find((m) => m.label === "seed0-noprosody");
    expect(withProsody?.mappingSha256).not.toBe(without?.mappingSha256);
  });

  it("reveal_after leaves fewer tokens vacated than the pure case at the same p", () => {
    const pure = golden.cases.find((c) => c.label === "seed0-p0.7");
    const reveal = golden.cases.find((c) => c.label === "control-reveal-after-2");
    expect(reveal?.params.p).toBe(pure?.params.p);
    expect(reveal?.stats.tokensVacated as number).toBeLessThan(pure?.stats.tokensVacated as number);
  });

  it("no divergence remains, and any that appeared would still be constrained", () => {
    // The two stacks now agree on every case, so this list is EMPTY — asserted, because a
    // fixture that quietly reacquired an exemption would look exactly like a green run.
    const flagged = golden.cases.filter((c) => c.knownDivergence !== undefined);
    expect(flagged.map((c) => c.label)).toEqual([]);

    // The rest of this test is the constraint the mechanism carries, kept live for the day
    // it is needed again: a divergence may appear only on a CONTROL case, it must carry the
    // explanation and the status, and it may never cover a count the control exists to
    // produce. A mapped-condition case acquiring one would mean the invariance theorem's
    // own arm had stopped agreeing.
    for (const gc of flagged) {
      const d = gc.knownDivergence as GoldenDivergence;
      expect(gc.params.consistent && gc.params.revealAfter === 0).toBe(false);
      expect(d.cause.length).toBeGreaterThan(80);
      expect(d.status).toContain("neither implementation was modified");
      expect(d.fields.length).toBeGreaterThan(0);
      for (const f of d.fields) expect(f.python).not.toBe(f.typescript);
    }
    // The counts a control exists to produce must agree in BOTH stacks — a divergence there
    // would mean SC-705's measurement itself had moved, which no exemption may cover.
    for (const gc of flagged) {
      const names = new Set((gc.knownDivergence as GoldenDivergence).fields.map((f) => f.field));
      expect(names.has("stats.tokensVacated")).toBe(false);
      expect(names.has("stats.stemsVacated")).toBe(false);
      expect(names.has("stats.domainTypesVacated")).toBe(false);
    }
  });

  it("consistent = false holds the vacancy rate but destroys the identity", () => {
    const pure = golden.cases.find((c) => c.label === "seed0-p0.7");
    const control = golden.cases.find((c) => c.label === "control-inconsistent");
    // Same rate — that is what makes it a control and not just a different transform.
    expect(control?.stats.tokensVacated).toBe(pure?.stats.tokensVacated);
    // Different text, because each occurrence gets its own type.
    expect(control?.vacatedSha256).not.toBe(pure?.vacatedSha256);
  });

  it("consistent = false vacates EVERYTHING at p = 1, seed 7 — the `tak` regression", () => {
    // §5.8, condition B on the per-occurrence path. `tak` (the stem of `taking`) once minted
    // the nonce `tak` at seed 7, so `Taking -> Taking` and one token silently survived the
    // transform: 1921 corpus types and 8201 tokens against the consistent path's 1922/8202.
    // A control whose vacancy rate is not the stated rate is not a control, so the identity
    // §10 states at `p = 1` — every eligible type vacates — has to hold here too.
    const control = golden.cases.find((c) => c.label === "control-inconsistent-seed7");
    const pure = golden.cases.find((c) => c.label === "seed7-p1.0");
    expect(control).toBeDefined();
    expect(control?.params.consistent).toBe(false);
    expect(control?.params.p).toBe(1);
    expect(control?.stats.corpusTypesVacated).toBe(1922);
    expect(control?.stats.tokensVacated).toBe(8202);
    expect(control?.stats.corpusTypesVacated).toBe(control?.stats.corpusTypesEligible);
    // The consistent path at the same seed and `p` reads the same counts; only the text
    // differs, which is exactly what this control is for.
    expect(control?.stats.corpusTypesVacated).toBe(pure?.stats.corpusTypesVacated);
    expect(control?.stats.tokensVacated).toBe(pure?.stats.tokensVacated);
    expect(control?.vacatedSha256).not.toBe(pure?.vacatedSha256);
  });
});

