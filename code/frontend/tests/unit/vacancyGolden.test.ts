/**
 * Golden-vector parity for the VACANCY TRANSFORM: the TypeScript engine vs the real
 * Python one, on the real committed corpus.
 *
 * `specs/007-vacancy-transform-field/architecture.md` §11 requires this file and names
 * exactly what it must pin. SC-706 requires the two implementations to agree — strings and
 * id streams EXACTLY, floats within `tolerance`. This test is that proof, and it follows
 * `lexGolden.test.ts` (feature 006) and `geoEngine.test.ts` (feature 003): a Python script
 * runs the REAL backend and writes what it measured; this file runs the REAL browser
 * engine against the same inputs and asserts.
 *
 * The fixture is `tests/fixtures/vacancy-golden.json`, regenerated by
 *
 *     python scripts/export_vacancy_golden.py
 *
 * and it records the git sha, the command, the corpus digest and each case's parameters.
 * `TOLERANCE` is read FROM the file rather than declared here, so the exporter and this
 * test cannot drift apart — the same discipline `lexGolden.test.ts` keeps.
 *
 * WHAT IS PINNED, per §11:
 *
 *   1. `vacancyU` for 24 stems spanning eligible/ineligible and both budgets, compared as
 *      the EXACT double. That exactness is the point of departure 2 (§4): `u` shifts a
 *      64-bit digest right by 11 before dividing by 2^53, so the numerator is exactly
 *      representable and Python and JavaScript get THE SAME double rather than two
 *      neighbours that straddle a `p` boundary.
 *   2. The FULL stem -> nonce map at seed 0 and seed 7 — every pair, both directions of
 *      the size check, plus `remintRounds` / `bijective` / `imageSize`.
 *   3. The first 400 characters of the vacated corpus at each `p`, exactly; plus the
 *      sha256 of the WHOLE 86 kB rewrite, which is the same assertion at 64 bytes.
 *   4. Every §10 statistic, at `p in {0, 0.25, 0.35, 0.5, 0.7, 0.75, 1}` and both seeds.
 *   5. Nesting as explicit SETS: `vacated(0.35) ⊆ vacated(0.7) ⊆ vacated(1)`, checked
 *      against the literal stem lists rather than against an assertion this language makes
 *      about itself (SC-701).
 *   6. Stability: each pinned stem's surface form at every `p`, and — derived across the
 *      cases — the fact that it is byte-identical at every `p` where the stem is vacated
 *      (SC-702).
 *   7. The token-id-stream digest under the mapped vocabulary at each `p`. All of them are
 *      EQUAL, across both seeds and both `matchProsody` settings: the invariance theorem
 *      of §7.3 / SC-703 pinned as DATA rather than as an assertion written twice.
 *   8. Both control conditions and both `matchProsody` settings.
 *
 * COMPARISON RULE. Strings, digests, counts, booleans and `u` are compared with `toBe` —
 * exact. Only the six prosody means (`meanSyllables*`, `meanAnapest*`, `stressFrom*`) use
 * `tolerance`, and the measured worst deviation is printed at the end of the run so a
 * silent creep toward the bound is visible.
 *
 * NO KNOWN DIVERGENCES REMAIN. Every case here — both seeds, both `matchProsody` settings,
 * every `p`, and all three controls — agrees field for field, string for string, digest for
 * digest. Three earlier disagreements were pinned in this file rather than hidden, and each
 * was retired by fixing the stack the contract said was wrong, never by loosening a
 * comparison:
 *
 *   1. `control-reveal-after-2`: `corpusTypesVacated` read 665 in Python and 1337 here,
 *      because Python MEASURED the count from the two texts while this engine computed it
 *      through the map. §10 defines `corpusTypes*` as what the panel shows a READER — i.e.
 *      what the text does — so the measured reading was the contract's. `vacancyStats` now
 *      measures the texts; `domainTypes*` keeps map membership, which §10 also requires.
 *   2. `control-inconsistent`: the two stacks minted DIFFERENT per-occurrence nonces. §5.8
 *      pins the key as `${stem}#${idx}` and §5.5's mint read its stress pattern off the
 *      string it was handed, so Python got `stress("little#0") = "10"` where this engine
 *      gets `stress("little") = "100"` — `Little` minted as `Wrerken` there and `Wrerkenle`
 *      here. §7.1 says the nonce carries THE STEM's syllable count and stress, so the key
 *      must not reach the prosody lookup; Python's `_mint` now takes `stem` separately.
 *   3. Condition B on the per-occurrence path (§5.8). It was enforced when building the map
 *      and not in the `consistent = false` control, so at seed 7, `p = 1`, the stem `tak`
 *      minted the nonce `tak` and `Taking -> Taking`: one token silently failed to vacate.
 *      Both stacks now forbid a per-occurrence nonce from equalling the stem it replaces as
 *      well as any domain type, and `control-inconsistent-seed7` pins the result — 1922
 *      corpus types and 8202 tokens vacated, exactly what `consistent = true` reads.
 *
 * The `knownDivergence` mechanism itself stays: it carries both readings per field, this
 * test asserts each side against its own, and `attach_divergence` in the exporter refuses to
 * write a fixture at all once Python starts agreeing with a recorded TypeScript value. That
 * guard is what retired all three entries above, and it is what an outstanding cross-stack
 * defect would use again.
 */

