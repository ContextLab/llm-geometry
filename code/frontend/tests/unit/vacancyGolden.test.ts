// --- the real corpus, the same bytes both stacks use ----------------------------------

const CORPUS_ASSET = path.resolve(__dirname, "../../public/static-data/lex/corpus.json");
const CORPUS = (JSON.parse(fs.readFileSync(CORPUS_ASSET, "utf-8")) as LexCorpusAsset).text;
const CORPUS_TYPES = new Set(tokenize(CORPUS));
const DOMAIN = vacancyDomain(CORPUS_TYPES);
/** The corpus's per-type occurrence counts — the frequency source `mint = "swap"` ranks by. */
const COUNTS = typeCounts(tokenize(CORPUS));
const BUDGET_WORDS = dolchBudget("full");

const sha256 = (s: string): string => createHash("sha256").update(s, "utf8").digest("hex");

/** The exporter's canonical form for a map digest: `stem\tnonce\n`, stems ASCII-ascending. */
function mappingSha256(mapping: ReadonlyMap<string, string>): string {
  const stems = [...mapping.keys()].sort();
  return sha256(stems.map((s) => `${s}\t${mapping.get(s)}\n`).join(""));
}

function paramsOf(c: GoldenCase): VacancyParams {
  return vacancyParams({
    p: c.params.p,
    seed: c.params.seed,
    consistent: c.params.consistent,
    matchProsody: c.params.matchProsody,
    revealAfter: c.params.revealAfter,
    keep: c.params.keep,
    mint: c.params.mint,
  });
}

/**
 * A FRESH map per case, always. Under `consistent = false` the rewrite writes the stress
 * pattern of every form it mints onto `vmap.mintedStress`, so a map shared between cases
 * would score one case's text against another case's minted patterns. The exporter builds
 * fresh maps for the controls for the same reason; doing it for every case here also
 * proves that reuse is irrelevant in the mapped condition.
 */
function mapFor(params: VacancyParams): VacancyMap {
  // `typeCounts` is passed unconditionally. `mint = "nonce"` ignores it — the nonce map is a
  // pure function of `(domain, seed, matchProsody)`, and every pre-existing case in this
  // fixture proves it by still matching — while `mint = "swap"` needs it and throws without
  // it. Passing it always is what keeps the two call sites from differing by what one of
  // them remembered, which is §5.2's whole objection to an optional `avoid`.
  return buildVacancyMap(DOMAIN, params, COUNTS);
}

/** The fixture's own reading of a field a `knownDivergence` block names. */
function goldenField(gc: GoldenCase, field: string): string | number | boolean {
  if (field.startsWith("stats.")) {
    const name = field.slice("stats.".length);
    const value = gc.stats[name];
    if (value === undefined) throw new Error(`vacancy-golden.json: no stat ${name}`);
    return value;
  }
  if (field === "head400") return gc.head400;
  if (field === "vacatedSha256") return gc.vacatedSha256;
  if (field === "vacatedChars") return gc.vacatedChars;
  throw new Error(`vacancy-golden.json: unknown divergence field ${field}`);
}

/** Every float in this fixture is order-1 or smaller, so absolute deviation is the honest read. */
const deviations: { what: string; dev: number }[] = [];
function expectClose(actual: number, expected: number, what: string): void {
  const dev = Math.abs(actual - expected);
  deviations.push({ what, dev });
  expect(dev, `${what}: ${actual} vs golden ${expected}`).toBeLessThanOrEqual(TOLERANCE);
}

