/**
 * Golden-vector parity: the TypeScript Lexicon Lab engine vs the real PyTorch one.
 *
 * SC-605 of `specs/006-lexicon-lab-tiny/spec.md` requires the two implementations of
 * `specs/006-lexicon-lab-tiny/architecture.md` to agree to <= 1e-5. This file is that
 * proof. It follows the pattern feature 003 established for the Geometry Lab
 * (`scripts/export_static_assets.py` -> `tests/fixtures/geo/golden.json` ->
 * `geoEngine.test.ts`): a Python script runs the REAL backend and writes what it
 * measured; this test runs the REAL browser engine against the same inputs and asserts.
 *
 * The fixture is `tests/fixtures/lex-golden.json`, regenerated by
 *
 *     python scripts/export_lex_golden.py
 *
 * and it records the git sha, the command, and each case's configuration.
 *
 * Coverage, across three configurations that vary d_model, n_layers, n_heads and
 * tied/untied together:
 *
 *   1. a FIXED weight set, spelled out in the fixture, so both engines start from
 *      identical numbers — architecture.md explicitly does not claim RNG parity
 *      ("non-portable RNG streams"), so seeded-init agreement would prove nothing;
 *   2. forward-pass logits for a fixed token sequence;
 *   3. the loss for a fixed (input, target) pair, with a `<pad>` target so
 *      `ignore_index` is exercised;
 *   4. every spectrum statistic — effective/stable rank, participation ratio,
 *      frac_var_top2/top10, n_dims_for_90pct, the ceiling, the leading singular values,
 *      and the PCA coordinates + explained-variance ratios;
 *   5. real gradients, their global norm, and the weights after ONE AdamW step at a
 *      known LR, so the training math is covered and not only inference;
 *   6. the one-cycle LR schedule at several step indices.
 *
 * DEVIATION METRIC. Every comparison reports
 *
 *     dev = |actual - golden| / max(1, |actual|, |golden|)
 *
 * i.e. relative deviation for order-1-and-larger quantities, absolute deviation for
 * small ones — a single number that is <= 1e-5 only if BOTH readings are. The measured
 * maximum per category is printed at the end of the run.
 *
 * Note on precision: the backend computes in float32 and this engine in float64 (the
 * geoEngine house convention), so exact equality is neither expected nor claimed; 1e-5
 * is the contract's tolerance and it is asserted here, never widened.
 *
 * ONE MEASURED EXCEPTION, and it is a property of AdamW rather than of either engine.
 * On the FIRST step, `t = 1` makes `m̂ = g` and `sqrt(v̂) = |g|`, so the update is
 *
 *     -lr · g / (|g| + 1e-8)
 *
 * which for any `|g|` above the epsilon is `-lr · sign(g)` REGARDLESS of the gradient's
 * magnitude. A parameter whose true gradient is at or below that epsilon therefore has
 * its step decided by each backend's roundoff, and float32 vs float64 disagree there by
 * up to a full `lr`. The largest such family is structural and provably so: the KEY BIAS
 * `qkv_b[d:2d]` has an EXACTLY ZERO gradient, because adding a constant `b_k` to every
 * key shifts `scores_ij = q_i·k_j` by `q_i·b_k`, constant along `j`, and softmax is
 * invariant to a constant shift along the axis it normalizes. This engine computes ~1e-18
 * there and torch's float32 computes ~1e-9; both are zero, and AdamW amplifies the
 * difference to ~1e-4.
 *
 * So post-step weights are split by the optimizer's OWN constant: entries whose golden
 * gradient has `|g| >= ADAM_EPS` are held to 1e-5 (measured worst: 2.1e-6 across all
 * three configurations); entries below it are held to the bound a single step can move
 * them, and their count is asserted to stay a small fraction so the exception can never
 * quietly grow to hide a real regression. Nothing else in this file is exempted.
 */

